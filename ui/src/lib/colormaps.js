export function mapColor(name, v) {
  v = Math.max(0, Math.min(1, v))
  const s = MAPS[name]
  let i = 0
  while (i < s.length - 2 && v > s[i + 1][0]) i++
  const a = s[i]
  const b = s[i + 1]
  const t = (v - a[0]) / (b[0] - a[0] || 1)
  return [
    a[1] + (b[1] - a[1]) * t,
    a[2] + (b[2] - a[2]) * t,
    a[3] + (b[3] - a[3]) * t,
  ]
}
